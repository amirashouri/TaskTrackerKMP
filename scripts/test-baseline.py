#!/usr/bin/env python3
"""Generate test-baseline.json from the JUnit XML Gradle has already written.

The three host totals used to be hand-copied into `AGENTS.md` and `Project.md` and
they drifted out of step more than once (the two tables once disagreed by a whole
task's-worth of tests). Counts are a build artifact, so they are generated here and
checked in; the prose points at this file instead of restating the numbers.

The generated file records the *identity* of every failure, not just the count. That is
what lets `scripts/check-baseline.sh` tell "the same twelve tests are red" from "one was
fixed and another broke", which a count alone cannot.

Depends on nothing outside the standard library.

  scripts/test-baseline.py                    # rewrite test-baseline.json
  scripts/test-baseline.py --out /tmp/x.json  # write elsewhere (used by the checker)
  scripts/test-baseline.py --hosts jvmTest    # one host only, for a partial run
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys
import xml.etree.ElementTree as ET

HOSTS = ("jvmTest", "iosSimulatorArm64Test", "testAndroidHostTest")

TARGETS = {
    "jvmTest": "jvm",
    "iosSimulatorArm64Test": "iosSimulatorArm64",
    "testAndroidHostTest": "androidHost",
}

# Kotlin/Native prefixes a test's XML class name with the *task* name, and both JVM and
# Native append the host to the method name. Neither is part of the test's identity: the
# host is already the key this file groups by, so normalise both away and let the same
# test compare across hosts where its class names genuinely match.
CLASS_PREFIXES = ("jvmTest.", "iosSimulatorArm64Test.", "testAndroidHostTest.")

HOST_SUFFIXES = {
    "jvmTest": "[jvm]",
    "iosSimulatorArm64Test": "[iosSimulatorArm64]",
    "testAndroidHostTest": None,
}


def normalise(host: str, classname: str, name: str) -> str:
    for prefix in CLASS_PREFIXES:
        if classname.startswith(prefix):
            classname = classname[len(prefix):]
            break

    suffix = HOST_SUFFIXES.get(host)
    if suffix and name.endswith(suffix):
        name = name[:-len(suffix)]

    return f"{classname}#{name}"


def totals(host: str) -> dict:
    counts = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0}
    failed: set[str] = set()
    paths = glob.glob(f"**/build/test-results/{host}/TEST-*.xml", recursive=True)

    for path in paths:
        root = ET.parse(path).getroot()
        for key in counts:
            counts[key] += int(root.get(key) or 0)

        for case in root.iter("testcase"):
            if any(child.tag in ("failure", "error") for child in case):
                failed.add(
                    normalise(
                        host,
                        case.get("classname") or "",
                        case.get("name") or "",
                    )
                )

    counts["failed"] = sorted(failed)
    counts["resultFiles"] = len(paths)
    return counts


def selected_hosts(raw: str | None) -> list[str]:
    if not raw:
        return list(HOSTS)

    hosts = [part.strip() for part in raw.split(",") if part.strip()]
    unknown = [host for host in hosts if host not in HOSTS]
    if unknown:
        raise SystemExit(
            f"unknown host(s): {', '.join(unknown)} (use {', '.join(HOSTS)})"
        )
    return hosts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="test-baseline.json")
    parser.add_argument(
        "--hosts",
        default=None,
        help="comma-separated host tasks to measure; default: all three",
    )
    args = parser.parse_args()

    if not os.path.isdir("."):
        print("run from the repository root", file=sys.stderr)
        return 2

    hosts = selected_hosts(args.hosts)
    if args.out == "test-baseline.json" and set(hosts) != set(HOSTS):
        print(
            "refusing to write a partial test-baseline.json; "
            "run all three hosts or use --out for a temporary file",
            file=sys.stderr,
        )
        return 2
    measured = {host: totals(host) for host in hosts}

    # A partial run must not be written over the committed baseline by accident, and a
    # host with no XML at all is a missing run rather than zero tests. Both are failures:
    # a baseline built from a subset is exactly the stale-number problem this file exists
    # to remove.
    empty = [
        host
        for host, row in measured.items()
        if row["resultFiles"] == 0 or row["tests"] == 0
    ]
    if empty:
        print(
            "no test results for: "
            + ", ".join(empty)
            + "\nrun the host first (scripts/check.sh <host> or full), then regenerate.",
            file=sys.stderr,
        )
        return 2

    data = {
        "note": (
            "Generated by scripts/test-baseline.py from "
            "**/build/test-results/*/TEST-*.xml. Do not hand-edit: run "
            "`scripts/check.sh full`, then this script."
        ),
        "hosts": {
            host: {"target": TARGETS[host], **measured[host]} for host in hosts
        },
    }

    with open(args.out, "w") as handle:
        json.dump(data, handle, indent=2)
        handle.write("\n")

    for host, row in data["hosts"].items():
        print(
            f"{host:<24} {row['tests']:>5} tests, {row['failures']:>3} failed, "
            f"{row['errors']} errors, {row['skipped']} skipped"
        )
    if args.out == "test-baseline.json":
        print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
