#!/usr/bin/env python3
"""Generate test-baseline.json from the JUnit XML Gradle has already written.

The three host totals used to be hand-copied into `AGENTS.md` and `Project.md` and
they drifted out of step more than once (the two tables once disagreed by a whole
task's-worth of tests). Counts are a build artifact, so they are generated here and
checked in; the prose points at this file instead of restating the numbers.

Depends on nothing outside the standard library.

  scripts/test-baseline.py                 # rewrite test-baseline.json
  scripts/test-baseline.py --out /tmp/x.json   # write elsewhere (used by the checker)
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys
import xml.etree.ElementTree as ET

HOSTS = ["jvmTest", "iosSimulatorArm64Test", "testAndroidHostTest"]

# Which module owns how many failures — only the Android host fails in bulk, and the
# split is the interesting part (it is a viewport fact, not a behaviour fact).
META = {
    "jvmTest": {"target": "jvm", "exit": "red", "why": "three pre-existing failures"},
    "iosSimulatorArm64Test": {"target": "iosSimulatorArm64", "exit": "red", "why": "the same three"},
    "testAndroidHostTest": {"target": "androidHost", "exit": "red", "why": "Robolectric viewport and rasteriser"},
}


def totals(host: str) -> dict[str, int]:
    counts = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0}
    for path in glob.glob(f"**/build/test-results/{host}/TEST-*.xml", recursive=True):
        root = ET.parse(path).getroot()
        for key in counts:
            counts[key] += int(root.get(key) or 0)
    return counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="test-baseline.json")
    args = parser.parse_args()

    data = {
        "note": "Generated by scripts/test-baseline.py from **/build/test-results/*/TEST-*.xml. "
                "Do not hand-edit: run `scripts/check.sh all`, then this script.",
        "hosts": {h: {**META[h], **totals(h)} for h in HOSTS},
    }

    if not os.path.isdir("."):
        print("run from the repository root", file=sys.stderr)
        return 2

    with open(args.out, "w") as fh:
        json.dump(data, fh, indent=2)
        fh.write("\n")

    for host, row in data["hosts"].items():
        print(f"{host:<24} {row['tests']:>5} tests, {row['failures']:>3} failed, "
              f"{row['errors']} errors, {row['skipped']} skipped")
    if args.out == "test-baseline.json":
        print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
